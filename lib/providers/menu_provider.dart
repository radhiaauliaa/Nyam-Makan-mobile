// providers/menu_provider.dart
import 'package:flutter/foundation.dart';
import '../models/menu_model.dart';
import '../services/menu_service.dart';

class MenuProvider with ChangeNotifier {
  final MenuService _menuService = MenuService();

  List<Menu> _menuItems = [];
  bool _isLoading = false;
  String? _error;

  List<Menu> get menuItems => _menuItems;
  bool get isLoading => _isLoading;
  String? get error => _error;

  Future<void> loadRestaurantMenu(String restaurantId) async {
    _isLoading = true;
    _error = null;
    notifyListeners();

    try {
      _menuItems = await _menuService.getMenusByRestaurantId(restaurantId);
      _error = null;
    } catch (e) {
      _error = e.toString();
    } finally {
      _isLoading = false;
      notifyListeners();
    }
  }

  // PERBAIKAN: Method untuk create menu
  Future<bool> createMenuItem(Menu menuItem) async {
    _error = null;
    _isLoading = true;
    notifyListeners();

    try {
      // Generate new ID jika belum ada
      final menuToSave = menuItem.id.isEmpty
          ? Menu(
              id: '', // Will be generated by Firestore
              restaurantId: menuItem.restaurantId,
              name: menuItem.name,
              description: menuItem.description,
              price: menuItem.price,
              originalPrice: menuItem.originalPrice,
              category: menuItem.category,
              images: menuItem.images,
              imageUrl: menuItem.imageUrl,
              isPopular: menuItem.isPopular,
              rating: menuItem.rating,
              reviewCount: menuItem.reviewCount,
              isAvailable: menuItem.isAvailable,
              tags: menuItem.tags,
              createdAt: DateTime.now(),
              updatedAt: DateTime.now(),
            )
          : menuItem;

      final newMenuId = await _menuService.createMenu(menuToSave);
      
      // Reload data setelah berhasil
      await loadRestaurantMenu(menuItem.restaurantId);
      
      return true;
    } catch (e) {
      _error = 'Gagal menyimpan menu: $e';
      notifyListeners();
      return false;
    } finally {
      _isLoading = false;
      notifyListeners();
    }
  }

  // PERBAIKAN: Method untuk update menu
  Future<bool> updateMenuItem(Menu menuItem) async {
    _error = null;
    _isLoading = true;
    notifyListeners();

    try {
      // Update updatedAt timestamp
      final updatedMenu = Menu(
        id: menuItem.id,
        restaurantId: menuItem.restaurantId,
        name: menuItem.name,
        description: menuItem.description,
        price: menuItem.price,
        originalPrice: menuItem.originalPrice,
        category: menuItem.category,
        images: menuItem.images,
        imageUrl: menuItem.imageUrl,
        isPopular: menuItem.isPopular,
        rating: menuItem.rating,
        reviewCount: menuItem.reviewCount,
        isAvailable: menuItem.isAvailable,
        tags: menuItem.tags,
        createdAt: menuItem.createdAt,
        updatedAt: DateTime.now(),
      );

      await _menuService.updateMenu(updatedMenu);
      
      // Reload data setelah berhasil
      await loadRestaurantMenu(menuItem.restaurantId);
      
      return true;
    } catch (e) {
      _error = 'Gagal update menu: $e';
      notifyListeners();
      return false;
    } finally {
      _isLoading = false;
      notifyListeners();
    }
  }

  // PERBAIKAN: Method untuk delete menu
  // providers/menu_provider.dart - update deleteMenuItem
Future<bool> deleteMenuItem(String menuItemId, String restaurantId) async {
  _error = null;
  _isLoading = true;
  notifyListeners();

  try {
    // 1. Hapus dari Firestore
    await _menuService.deleteMenu(menuItemId);
    
    // 2. Hapus dari local list langsung (tanpa reload dari Firestore)
    _menuItems.removeWhere((item) => item.id == menuItemId);
    
    // 3. Notify UI bahwa data berubah
    notifyListeners();
    
    return true;
  } catch (e) {
    _error = 'Gagal menghapus menu: $e';
    return false;
  } finally {
    _isLoading = false;
    notifyListeners();
  }
}

  void clearError() {
    _error = null;
    notifyListeners();
  }
}